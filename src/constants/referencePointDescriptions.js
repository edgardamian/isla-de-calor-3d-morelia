/**
 * Normalizes string to match description key
 */
export function getReferencePointDescription(name) {
  if (!name) return null;
  const key = name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();

  // Try direct or fuzzy match
  for (const [k, data] of Object.entries(REFERENCE_POINTS_INFO)) {
    const normK = k
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');
    if (normK === key || key.includes(normK) || normK.includes(key)) {
      return data;
    }
  }

  return {
    category: 'Punto de Interés',
    desc: `Hito urbano e infraestructura de referencia en la Zona Metropolitana de Morelia.`,
    badgeColor: 'bg-sky-500/20 text-sky-300 border-sky-500/40',
  };
}
